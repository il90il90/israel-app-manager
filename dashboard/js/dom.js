// Safe DOM building. Every piece of text is set with textContent and every URL is checked,
// so catalog data, app-manager.json files and API answers can never inject markup or script.
// (The Content-Security-Policy in index.html is the second line of defence.)

const SVG_NS = "http://www.w3.org/2000/svg";

/** Only https: (and, for images we generate, data:image/png) URLs are ever put into the page. */
export function safeUrl(value, { allowDataImage = false } = {}) {
  if (typeof value !== "string") return null;
  try {
    const url = new URL(value);
    if (url.protocol === "https:" && !url.username && !url.password) return url.href;
    // This site's own files (the page is served over https on GitHub Pages; http only in local tests).
    if (typeof location !== "undefined" && url.origin === location.origin) return url.href;
    if (allowDataImage && /^data:image\/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+$/.test(value)) return value;
  } catch {
    /* not a URL */
  }
  return null;
}

/**
 * h("button", {class: "btn", onclick: fn, disabled: true}, "Text", child, [more])
 * Attributes named on* take functions. href/src go through safeUrl. Strings become text nodes.
 */
export function h(tag, attrs = {}, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs ?? {})) {
    if (value === undefined || value === null || value === false) continue;
    if (key.startsWith("on") && typeof value === "function") {
      el.addEventListener(key.slice(2).toLowerCase(), value);
    } else if (key === "class") {
      el.className = Array.isArray(value) ? value.filter(Boolean).join(" ") : value;
    } else if (key === "style") {
      // Through the CSSOM: the Content-Security-Policy (style-src 'self') blocks style attributes.
      el.style.cssText = String(value);
    } else if (key === "dataset") {
      Object.assign(el.dataset, value);
    } else if (key === "href" || key === "src") {
      const url = key === "src" ? safeUrl(value, { allowDataImage: true }) : safeUrl(value);
      if (url) el.setAttribute(key, url);
    } else if (key === "value" && "value" in el) {
      el.value = value;
    } else if (key === "checked" || key === "selected" || key === "disabled" || key === "required" || key === "readOnly" || key === "open") {
      el[key] = Boolean(value);
    } else if (value === true) {
      el.setAttribute(key, "");
    } else {
      el.setAttribute(key, String(value));
    }
  }
  append(el, children);
  if (tag === "a" && el.getAttribute("target") === "_blank") el.setAttribute("rel", "noopener noreferrer");
  return el;
}

export function append(parent, children) {
  for (const child of children.flat(Infinity)) {
    if (child === null || child === undefined || child === false) continue;
    parent.append(child instanceof Node ? child : document.createTextNode(String(child)));
  }
  return parent;
}

export function clear(el) {
  while (el.firstChild) el.firstChild.remove();
  return el;
}

